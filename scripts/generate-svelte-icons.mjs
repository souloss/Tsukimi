import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { glob } from "glob";

const projectRoot = path.resolve(
	path.dirname(fileURLToPath(import.meta.url)),
	"..",
);
const outputPath = path.join(
	projectRoot,
	"src/generated/svelte-icon-collections.ts",
);

const collectionPackages = {
	"eos-icons": "@iconify-json/eos-icons",
	"fa7-solid": "@iconify-json/fa7-solid",
	"material-symbols": "@iconify-json/material-symbols",
	mdi: "@iconify-json/mdi",
	"svg-spinners": "@iconify-json/svg-spinners",
};

const iconNames = new Map(
	Object.keys(collectionPackages).map((prefix) => [prefix, new Set()]),
);
const sourceFiles = await glob("src/**/*.svelte", {
	cwd: projectRoot,
	absolute: true,
});
const iconLiteralPattern = /["'`]([a-z][a-z0-9-]*:[a-z0-9][a-z0-9-]*)["'`]/g;

for (const sourceFile of sourceFiles) {
	const source = await readFile(sourceFile, "utf8");
	for (const match of source.matchAll(iconLiteralPattern)) {
		const [prefix, name] = match[1].split(":");
		iconNames.get(prefix)?.add(name);
	}
}

const collections = [];
const missingIcons = [];

for (const [prefix, packageName] of Object.entries(collectionPackages)) {
	const requestedNames = [...iconNames.get(prefix)].sort();
	if (requestedNames.length === 0) {
		continue;
	}

	const iconSet = JSON.parse(
		await readFile(
			path.join(projectRoot, "node_modules", packageName, "icons.json"),
			"utf8",
		),
	);
	const icons = {};
	const aliases = {};

	const includeIcon = (name, resolving = new Set()) => {
		if (icons[name] || aliases[name]) {
			return;
		}
		if (iconSet.icons[name]) {
			icons[name] = iconSet.icons[name];
			return;
		}

		const alias = iconSet.aliases?.[name];
		if (!alias || resolving.has(name)) {
			missingIcons.push(`${prefix}:${name}`);
			return;
		}

		aliases[name] = alias;
		includeIcon(alias.parent, new Set([...resolving, name]));
	};

	for (const name of requestedNames) {
		includeIcon(name);
	}

	const collection = {
		prefix,
		icons,
	};
	if (Object.keys(aliases).length > 0) {
		collection.aliases = aliases;
	}
	if (iconSet.width) {
		collection.width = iconSet.width;
	}
	if (iconSet.height) {
		collection.height = iconSet.height;
	}
	collections.push(collection);
}

if (missingIcons.length > 0) {
	throw new Error(`Missing local icons: ${missingIcons.join(", ")}`);
}

const generatedSource = `// Generated by scripts/generate-svelte-icons.mjs. Do not edit manually.\n\nexport const localIconCollections = ${JSON.stringify(collections, null, "\t")} as const;\n`;
let currentSource = "";
try {
	currentSource = await readFile(outputPath, "utf8");
} catch {
	// The first run creates the generated file.
}

if (currentSource !== generatedSource) {
	await writeFile(outputPath, generatedSource);
}

const generatedCount = collections.reduce(
	(total, collection) =>
		total +
		Object.keys(collection.icons).length +
		Object.keys(collection.aliases ?? {}).length,
	0,
);
console.log(
	`Generated ${generatedCount} local Svelte icons from ${sourceFiles.length} components`,
);
