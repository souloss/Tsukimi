import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const manifestPath = resolve(root, "src/plugins/markdown-manifest.json");
const outputPath = resolve(root, "src/generated/markdown-capabilities.ts");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));

const capabilities = manifest.entries.map((entry) => ({
	id: entry.id,
	syntax: entry.syntax,
	runtime: entry.runtime ?? null,
}));

const source = `// Generated by scripts/generate-markdown-capabilities.mjs. Do not edit manually.
export const markdownCapabilities = ${JSON.stringify(capabilities, null, "\t")} as const;

export type MarkdownCapabilityId = (typeof markdownCapabilities)[number]["id"];
`;

await writeFile(outputPath, source);
console.log(`Generated markdown capability snapshot (${capabilities.length} entries).`);
