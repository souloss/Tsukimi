import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const manifest = JSON.parse(
	await readFile(resolve(root, "src/plugins/markdown-manifest.json"), "utf8"),
);
const output = resolve(root, "docs/generated/markdown-capabilities.md");
await mkdir(resolve(root, "docs/generated"), { recursive: true });
const rows = manifest.entries.map((entry) => {
	const runtime = entry.runtime
		? `按需加载 \`${entry.runtime.loader}\`（\`${entry.runtime.selector}\`）`
		: "构建期处理";
	return `| \`${entry.id}\` | \`${entry.syntax.replaceAll("|", "\\|")}\` | ${entry.implementation} | ${runtime} |`;
});
const content = `<!-- Generated by scripts/generate-markdown-docs.mjs. Do not edit manually. -->
# Markdown 能力清单

此表由 \`src/plugins/markdown-manifest.json\` 生成。带有运行时标记的能力只在页面实际出现对应语法时加载客户端资源。

| 能力 | 语法 | 实现 | 资源策略 |
| --- | --- | --- | --- |
${rows.join("\n")}
`;
await writeFile(output, content);
console.log(`Generated Markdown capability docs (${manifest.entries.length} entries).`);
